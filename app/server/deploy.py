    def _centos7_fix_repos(self):
        """CentOS 7 已 EOL，mirrorlist 全 404。切到 vault 归档源 + EPEL 归档。"""
        self._log("CentOS 7 源已失效，切换到 vault 归档源")
        return self.sh("\n".join([
            "set +e",
            "sed -i -e 's|^mirrorlist=|#mirrorlist=|g' "
            "-e 's|^#baseurl=http://mirror.centos.org|baseurl=http://vault.centos.org|g' "
            "/etc/yum.repos.d/CentOS-*.repo 2>/dev/null",
            "for f in /etc/yum.repos.d/epel*.repo; do",
            '  [ -f "$f" ] || continue',
            "  sed -i -e 's|^metalink=|#metalink=|g' "
            "-e 's|^#baseurl=https://download.fedoraproject.org/pub/epel|"
            "baseurl=https://archives.fedoraproject.org/pub/archive/epel|g' \"$f\"",
            "done",
            "yum clean all >/dev/null 2>&1",
            "echo REPO_FIXED",
        ]), timeout=180)

