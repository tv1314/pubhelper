    def st_frpc_local(self):
        tgz = self._frp_tarball()
        base = os.path.join(self.data_dir, "frp")
        os.makedirs(base, exist_ok=True)
        binpath = os.path.join(base, "frpc")
        if not (os.path.isfile(binpath) and os.access(binpath, os.X_OK)):
            tmp = os.path.join(base, "_x")
            if os.path.isdir(tmp):
                shutil.rmtree(tmp, ignore_errors=True)
            with tarfile.open(tgz, "r:gz") as tf:
                tf.extractall(tmp)
            src = None
            for root, _dirs, files in os.walk(tmp):
                if "frpc" in files:
                    src = os.path.join(root, "frpc")
                    break
            if not src:
                raise sshx.SSHError("安装包里没找到 frpc 二进制")
            shutil.copy2(src, binpath)
            os.chmod(binpath, 0o755)
            shutil.rmtree(tmp, ignore_errors=True)
        conf = os.path.join(base, "frpc.toml")
        with open(conf, "w", encoding="utf-8") as f:
            f.write(frpc_toml(self.cfg["vps"]["host"].strip(), self.frp_bind,
                              self.token, self.services,
                              logfile=os.path.join(base, "frpc.log")))
        os.chmod(conf, 0o600)
        self._frpc_conf = conf
        self._frpc_bin = binpath
        return "%d 条隧道定义" % len(self.services)

    def st_frpc_start(self):
        self._verify_local_frpc()
        base = os.path.join(self.data_dir, "frp")
        pidf = os.path.join(base, "frpc.pid")
        logf = os.path.join(base, "frpc.log")

        # 先收拾掉历史上 nohup 拉起的实例，避免两个 frpc 抢同一批 proxy
        _kill_pidfile(pidf)

        if systemd_ok():
            return self._start_via_systemd(base, logf)

        # 没有 systemd 才退回 nohup（无守护，进程挂了不会自动拉起）
        os.makedirs(base, exist_ok=True)
        with open(logf, "ab") as lf:
            lf.write(b"\n=== restart " + time.strftime("%F %T").encode() + b" ===\n")
        p = subprocess.Popen([self._frpc_bin, "-c", self._frpc_conf],
                             stdout=open(logf, "ab"), stderr=subprocess.STDOUT,
                             stdin=subprocess.DEVNULL, start_new_session=True)
        with open(pidf, "w") as f:
            f.write(str(p.pid))
        time.sleep(4)
        if p.poll() is not None:
            raise sshx.SSHError("frpc 启动即退出：\n%s" % _tail_file(logf, 600))
        tail = _tail_file(logf, 400)
        if "login to server success" not in tail and "start proxy success" not in tail:
            self._log("frpc 日志尾部：%s" % tail.replace("\n", " | ")[-300:])
        return "frpc pid=%d（无 systemd，未托管）" % p.pid

    def _start_via_systemd(self, base, logf):
        unit = frpc_unit(self.data_dir)
        try:
            with open(FRPC_UNIT_PATH, "w", encoding="utf-8") as f:
                f.write(unit)
            os.chmod(FRPC_UNIT_PATH, 0o644)
        except Exception as e:
            self._log("写 systemd 单元失败，退回 nohup：%s" % e)
            raise
        self._log("已写入 %s，由 systemd 托管（Restart=always）" % FRPC_UNIT_NAME)
        for cmd in (["systemctl", "daemon-reload"],
                    ["systemctl", "enable", FRPC_UNIT_NAME],
                    ["systemctl", "restart", FRPC_UNIT_NAME]):
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=90)
            if r.returncode != 0 and cmd[1] != "enable":
                raise sshx.SSHError("systemctl %s 失败：%s"
                                    % (" ".join(cmd[1:]), (r.stderr or r.stdout).strip()[:300]))
        time.sleep(4)
        r = subprocess.run(["systemctl", "is-active", FRPC_UNIT_NAME],
                           capture_output=True, text=True, timeout=30)
        if (r.stdout or "").strip() != "active":
            raise sshx.SSHError("frpc 服务未能保持运行：\n%s" % _tail_file(logf, 600))
        pid = _systemd_mainpid(FRPC_UNIT_NAME)
        tail = _tail_file(logf, 800) or _tail_file(os.path.join(base, "frpc.boot.log"), 800)
        if "login to server success" not in tail and "start proxy success" not in tail:
            self._log("frpc 日志尾部：%s" % tail.replace("\n", " | ")[-300:])
        return "frpc 已由 systemd 托管（pid %d，崩溃 5 秒后自动重启）" % pid

