    def _find_local_bundle(self, arch):
        """先找已缓存 / 应用包内置 / 用户手动放置的压缩包。"""
        cands = []
        cands.append(os.path.join(self.data_dir, FRP_CACHE_DIR))
        # 应用包内置（随 fpk 一起装上去）
        cands.append(os.path.join(os.path.dirname(os.path.abspath(__file__)), "bundle"))
        # 用户可能随手丢在这里
        cands.append(self.data_dir)
        for d in cands:
            if not os.path.isdir(d):
                continue
            names = sorted(os.listdir(d), reverse=True)
            for n in names:
                if not n.endswith(".tar.gz"):
                    continue
                if "_linux_%s" % arch not in n:
                    continue
                p = os.path.join(d, n)
                try:
                    if os.path.getsize(p) > 1000000:
                        return p
                except Exception:
                    pass
        return None

    def _vps_dl_script(self, urls):
        """在服务器上按顺序试各个源，成功即停。"""
        return "\n".join([
            "set +e",
            "rm -f /tmp/ph.tgz /tmp/pubhelper-frp.tar.gz",
            "for u in " + " ".join('"%s"' % u for u in urls) + "; do",
            # 8 秒连不上就换源；单源上限 240 秒；低于 20KB/s 持续 15 秒直接掐断
            '  curl -fsSL --connect-timeout 8 --max-time 240'
            ' --speed-limit 20480 --speed-time 15 -o /tmp/ph.tgz "$u"',
            '  sz=$(stat -c %s /tmp/ph.tgz 2>/dev/null || echo 0)',
            '  if [ "$sz" -gt 1000000 ]; then',
            "    mv /tmp/ph.tgz /tmp/pubhelper-frp.tar.gz",
            "    echo GOT_OK",
            "    break",
            "  fi",
            '  echo "fail: $u"',
            "done",
            "ls -l /tmp/pubhelper-frp.tar.gz 2>/dev/null",
            "echo PH_END",
        ])

    def _frp_tarball(self):
        """准备 frp 压缩包，返回本机路径。

        顺序刻意设计成「最快失败优先」：
          1) 本地已缓存 / 应用包内置 —— 零成本
          2) NAS 直连 —— 通的话几秒就下完；不通也会 5 秒内报错
          3) 借服务器网络下载再 scp 拉回 —— 慢但成功率高
        """
        arch = arch_to_frp(self.arch)
        cache = os.path.join(self.data_dir, FRP_CACHE_DIR)
        os.makedirs(cache, exist_ok=True)
        errs = []

        # ---- 1) 本地 ----
        local = self._find_local_bundle(arch)
        if local:
            self._log("使用本地安装包：%s（%.1f MB）"
                      % (os.path.basename(local), os.path.getsize(local) / 1048576.0))
            return local

        name = "frp_%s_linux_%s.tar.gz" % ("%s", arch)

        # ---- 2) NAS 直连（先试，失败很快）----
        for ver in self._frp_versions()[:1]:
            fn = name % ver
            path = os.path.join(cache, fn)
            for u in self._frp_urls(ver, fn):
                self._log("本机下载 %s" % u)
                try:
                    r = subprocess.run(
                        ["curl", "-L", "--connect-timeout", "8", "--max-time", "120",
                         "--speed-limit", "20480", "--speed-time", "15", "-o", path, u],
                        capture_output=True, text=True, timeout=140)
                except Exception as e:
                    errs.append("本机下载异常：%s" % e)
                    continue
                if (r.returncode == 0 and os.path.isfile(path)
                        and os.path.getsize(path) > 1000000):
                    self._log("本机下载成功（%.1f MB）" % (os.path.getsize(path) / 1048576.0))
                    return path
                errs.append("本机下载失败 rc=%s" % r.returncode)
                self._log("本机下载失败（rc=%s），换源" % r.returncode)

        # ---- 3) 借服务器网络 ----
        for ver in self._frp_versions()[:1]:
            fn = name % ver
            path = os.path.join(cache, fn)
            urls = self._frp_urls(ver, fn)
            self._log("改让服务器下载 frp v%s（单源最多 240 秒）" % ver)
            try:
                out = self.ssh.run_ok(self._vps_dl_script(urls), timeout=1100)
            except sshx.SSHError as e:
                errs.append("服务器下载失败：%s" % e)
                continue
            if "GOT_OK" not in out:
                errs.append("服务器下载 v%s 失败（GitHub 与镜像都不通）" % ver)
                self._log("服务器侧也没下到，4 个源全失败")
                continue
            try:
                self._log("服务器下载成功，回传中…")
                self.ssh.get_file("/tmp/pubhelper-frp.tar.gz", path, timeout=1800)
                self.ssh.run("rm -f /tmp/pubhelper-frp.tar.gz")
            except sshx.SSHError as e:
                errs.append("回传失败：%s" % e)
                continue
            if os.path.isfile(path) and os.path.getsize(path) > 1000000:
                self._log("已通过服务器获取 %s（%.1f MB）"
                          % (fn, os.path.getsize(path) / 1048576.0))
                return path

        raise sshx.SSHError(
            "拿不到 frp 安装包（本机与服务器都无法访问 GitHub）。\n"
            "把 frp_<版本>_linux_%s.tar.gz 放到 NAS 的 %s 后重新部署即可。\n"
            "明细：%s" % (arch, cache, "；".join(errs[-4:])))

