def detect_scheme(port, timeout=1.5):
    """探测本机某个端口说的是 HTTP 还是 HTTPS。

    返回 "https" / "http" / "unknown"。
    做法：先发一次 TLS 握手，能握上就是 https；握不上再发一句明文 HTTP，
    有 HTTP 响应就是 http；两者都不成立说明不是 HTTP 类服务（如 SSH/SMB）。
    """
    try:
        port = int(port)
    except Exception:
        return "unknown"

    # 1) TLS 探测
    try:
        ctx = ssl.create_default_context()
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
        raw = socket.create_connection(("127.0.0.1", port), timeout=timeout)
        try:
            tls = ctx.wrap_socket(raw, server_hostname="localhost")
            try:
                tls.close()
            except Exception:
                pass
            return "https"
        finally:
            try:
                raw.close()
            except Exception:
                pass
    except ssl.SSLError:
        pass                      # 不是 TLS，继续判断明文
    except Exception:
        pass                      # 连不上/超时，后面统一返回 unknown

    # 2) 明文 HTTP 探测
    try:
        s = socket.create_connection(("127.0.0.1", port), timeout=timeout)
        try:
            s.sendall(b"GET / HTTP/1.0\r\nHost: localhost\r\nConnection: close\r\n\r\n")
            data = s.recv(16)
            if data.startswith(b"HTTP/"):
                return "http"
        finally:
            try:
                s.close()
            except Exception:
                pass
    except Exception:
        pass
    return "unknown"

