def _tail_file(path, n=600):
    try:
        with open(path, "r", errors="replace") as f:
            return f.read()[-n:]
    except Exception:
        return ""


def _systemd_mainpid(unit):
    try:
        r = subprocess.run(["systemctl", "show", "-p", "MainPID", "--value", unit],
                           capture_output=True, text=True, timeout=20)
        return int((r.stdout or "0").strip() or 0)
    except Exception:
        return 0


def _kill_pidfile(pidf):
    """按 pid 文件干掉历史 nohup 实例。"""
    try:
        pid = int((open(pidf).read() or "0").strip() or 0)
    except Exception:
        pid = 0
    if pid and _pid_alive(pid):
        try:
            os.kill(pid, 15)
            for _ in range(20):
                if not _pid_alive(pid):
                    break
                time.sleep(0.25)
            if _pid_alive(pid):
                os.kill(pid, 9)
        except Exception:
            pass
    try:
        os.unlink(pidf)
    except Exception:
        pass


def _pid_alive(pid):
    if not pid:
        return False
    try:
        os.kill(pid, 0)
        return True
    except Exception:
        return False


def _pid_uptime(pid):
    if not pid:
        return 0
    try:
        r = subprocess.run(["ps", "-o", "etimes=", "-p", str(pid)],
                           capture_output=True, text=True, timeout=8)
        return int((r.stdout or "0").strip() or 0)
    except Exception:
        return 0


def _frp_dir(data_dir):
    return os.path.join(data_dir, "frp")


def frpc_state(data_dir):
    """返回本机 frpc 的运行状态。"""
    base = _frp_dir(data_dir)
    pidf = os.path.join(base, "frpc.pid")
    st = {
        "running": False,
        "pid": 0,
        "uptime": 0,
        "managed": "",
        "have_bin": os.path.isfile(os.path.join(base, "frpc")),
        "have_conf": os.path.isfile(os.path.join(base, "frpc.toml")),
    }

    # systemd 托管优先
    if os.path.isfile(FRPC_UNIT_PATH) and systemd_ok():
        st["managed"] = "systemd"
        try:
            r = subprocess.run(["systemctl", "is-active", FRPC_UNIT_NAME],
                               capture_output=True, text=True, timeout=15)
            if (r.stdout or "").strip() == "active":
                pid = _systemd_mainpid(FRPC_UNIT_NAME)
                st["running"] = True
                st["pid"] = pid
                st["uptime"] = _pid_uptime(pid)
            return st
        except Exception:
            pass

    try:
        pid = int((open(pidf).read() or "0").strip() or 0)
    except Exception:
        pid = 0
    if pid and _pid_alive(pid):
        st["running"] = True
        st["pid"] = pid
        st["managed"] = "nohup"
        st["uptime"] = _pid_uptime(pid)
    return st


def frpc_log_tail(data_dir, n=40):
    p = os.path.join(_frp_dir(data_dir), "frpc.log")
    try:
        with open(p, "r", errors="replace") as f:
            lines = f.read().splitlines()
        out = []
        for ln in lines[-n:]:
            out.append(re.sub(r"\x1b\[[0-9;]*m", "", ln))
        return out
    except Exception:
        return []


def frpc_stop(data_dir):
    base = _frp_dir(data_dir)
    pidf = os.path.join(base, "frpc.pid")
    st = frpc_state(data_dir)
    if not st["running"]:
        _kill_pidfile(pidf)
        return "隧道本来就没在运行"

    if st.get("managed") == "systemd":
        try:
            subprocess.run(["systemctl", "stop", FRPC_UNIT_NAME],
                           capture_output=True, text=True, timeout=60)
        except Exception as e:
            return "停止失败：%s" % e
        return "隧道已停止（systemd 服务已停，不会被自动拉起）"

    pid = st["pid"]
    _kill_pidfile(pidf)
    return "隧道已停止（pid %d）" % pid


def frpc_start(data_dir):
    base = _frp_dir(data_dir)
    binp = os.path.join(base, "frpc")
    conf = os.path.join(base, "frpc.toml")
    if not os.path.isfile(binp) or not os.path.isfile(conf):
        raise sshx.SSHError("本机还没有隧道配置，请先完成部署")
    st = frpc_state(data_dir)
    if st["running"]:
        return "隧道已在运行（pid %d）" % st["pid"]

    # 有 systemd 单元就走 systemctl，保证崩了会被自动拉起
    if os.path.isfile(FRPC_UNIT_PATH) and systemd_ok():
        try:
            subprocess.run(["systemctl", "start", FRPC_UNIT_NAME],
                           capture_output=True, text=True, timeout=120)
        except Exception as e:
            raise sshx.SSHError("启动 frpc 服务失败：%s" % e)
        time.sleep(3)
        st2 = frpc_state(data_dir)
        if not st2["running"]:
            raise sshx.SSHError("frpc 启动即退出：%s"
                                % " | ".join(frpc_log_tail(data_dir, 6))[-300:])
        return "隧道已启动（systemd 托管，pid %d）" % st2["pid"]

    logf = os.path.join(base, "frpc.log")
    try:
        with open(logf, "ab") as lf:
            lf.write(b"\n=== start " + time.strftime("%F %T").encode() + b" ===\n")
            out = lf
            p = subprocess.Popen([binp, "-c", conf], stdout=out, stderr=subprocess.STDOUT,
                                 stdin=subprocess.DEVNULL, start_new_session=True)
    except Exception as e:
        raise sshx.SSHError("启动 frpc 失败：%s" % e)
    with open(os.path.join(base, "frpc.pid"), "w") as f:
        f.write(str(p.pid))
    time.sleep(2.5)
    if p.poll() is not None:
        tail = " | ".join(frpc_log_tail(data_dir, 6))
        raise sshx.SSHError("frpc 启动即退出：%s" % tail[-300:])
    return "隧道已启动（pid %d）" % p.pid


# ---------------------------------------------------------------- 可达性探测
def _probe_one(url, timeout=5):
    t0 = time.time()
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "pubhelper/1"})
        with urllib.request.urlopen(req, timeout=timeout, context=ctx) as r:
            return {"code": r.status, "ms": int((time.time() - t0) * 1000)}
    except urllib.error.HTTPError as e:
        return {"code": e.code, "ms": int((time.time() - t0) * 1000)}
    except Exception as e:
        return {"code": 0, "ms": int((time.time() - t0) * 1000),
                "err": str(e)[:80]}


def resolve_ip(host, family="auto", timeout=3):
    """把地址解析成 IP；已经是 IP 就原样返回；失败返回空串。"""
    host = (host or "").strip().strip("[]")
    if not host:
        return ""
    try:
        socket.setdefaulttimeout(timeout)
        fam = socket.AF_UNSPEC
        if family == "ipv4":
            fam = socket.AF_INET
        elif family == "ipv6":
            fam = socket.AF_INET6
        infos = socket.getaddrinfo(host, None, fam, socket.SOCK_STREAM)
    except Exception:
        return ""
    finally:
        socket.setdefaulttimeout(None)
    want = []
    if family in ("auto", "ipv4"):
        want.append(socket.AF_INET)
    if family in ("auto", "ipv6"):
        want.append(socket.AF_INET6)
    for f in want:
        for it in infos:
            if it[0] == f:
                return it[4][0]
    for it in infos:
        return it[4][0]
    return ""


def service_urls(cfg):
    """按配置生成每个服务的对外访问地址。

    步骤②填了域名 → 用域名；没填 → 用解析出来的 IP（vps.ip）。
    vps.ip 为空时当场解析一次并回写，避免地址里出现域名。
    """
    dom = (cfg.get("domain") or "").strip()
    vps = cfg.get("vps") or {}
    if not vps.get("ip") and vps.get("host"):
        ip = resolve_ip(vps.get("host"), vps.get("family") or "auto")
        if ip:
            vps["ip"] = ip
    host = (vps.get("ip") or vps.get("host") or "").strip()
    base = dom or host or "服务器IP"
    out = []
    for s in cfg.get("services") or []:
        if not s.get("on"):
            continue
        port = int(s.get("public") or s.get("port"))
        if (s.get("proto") or "tcp") == "udp":
            out.append({"name": s.get("name") or str(port), "port": port,
                        "proto": "udp", "url": "udp://%s:%d" % (base, port),
                        "probe": False})
            continue
        scheme = "https" if (dom and cfg.get("use_https")) else "http"
        url = "%s://%s%s/" % (scheme, base, "" if port == 443 else ":%d" % port)
        out.append({"name": s.get("name") or str(port), "port": port,
                    "proto": "tcp", "url": url, "probe": True})
    return out


def probe_services(cfg, timeout=5):
    urls = service_urls(cfg)
    todo = [u for u in urls if u["probe"]]
    if todo:
        with concurrent.futures.ThreadPoolExecutor(max_workers=min(6, len(todo))) as ex:
            futs = dict((ex.submit(_probe_one, u["url"], timeout), u) for u in todo)
            for f in concurrent.futures.as_completed(futs, timeout=timeout + 6):
                u = futs[f]
                try:
                    u["result"] = f.result()
                except Exception as e:
                    u["result"] = {"code": 0, "err": str(e)[:60]}
    for u in urls:
        if not u["probe"]:
            u["result"] = None
    return urls
