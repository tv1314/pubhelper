    def _write_remote(self, path, content):
        """用 base64 落文件，避免任何转义问题。"""
        import base64
        b64 = base64.b64encode(content.encode("utf-8")).decode("ascii")
        self.sh("set -e\n"
                "mkdir -p $(dirname %s)\n"
                "printf %%s %s | base64 -d > %s\n"
                "chmod 600 %s\n" % (path, b64, path, path), timeout=60)

