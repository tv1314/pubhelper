    def st_firewall(self):
        ports = sorted({self.frp_bind, 80} | {s["public"] for s in self.tcp_svcs})
        script = ["set +e", "PKGS=''"]
        for p in ports:
            script += [
                "if command -v ufw >/dev/null 2>&1; then ufw allow %d/tcp >/dev/null 2>&1; fi" % p,
                "if command -v firewall-cmd >/dev/null 2>&1; then "
                "firewall-cmd --permanent --add-port=%d/tcp >/dev/null 2>&1; fi" % p,
            ]
        script += [
            "if command -v firewall-cmd >/dev/null 2>&1; then firewall-cmd --reload >/dev/null 2>&1; fi",
            "echo FW_DONE",
        ]
        self.sh("\n".join(script), timeout=180)
        return "已放行 %s" % ",".join(str(p) for p in ports)

