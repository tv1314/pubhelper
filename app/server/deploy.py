def frpc_toml(host, bind, token, services, logfile=""):
    lines = [
        "# generated by pubhelper",
        'serverAddr = "%s"' % host,
        "serverPort = %d" % bind,
        'auth.method = "token"',
        'auth.token = "%s"' % token,
        "",
        "# 断线无限重连，别退出进程",
        "loginFailExit = false",
        "transport.heartbeatInterval = 10",
        "transport.heartbeatTimeout = 30",
        "transport.tcpMux = true",
        "# 注意：0.52 起这里是 int（秒），不是 bool，写 true 会启动即崩溃",
        "transport.dialServerKeepalive = 7200",
        "# 预建空闲连接，降低 Web 界面首包延迟",
        "transport.poolCount = 5",
    ]
    if logfile:
        lines += [
            "",
            "# 日志：交给 frpc 自己写，按天轮转，避免无限增长",
            'log.to = "%s"' % logfile,
            'log.level = "info"',
            "log.maxDays = 7",
        ]
    lines.append("")
    for s in services:
        lines += [
            "[[proxies]]",
            'name = "ph-%d-%s"' % (s["port"], s["proto"]),
            'type = "%s"' % s["proto"],
            'localIP = "127.0.0.1"',
            "localPort = %d" % s["port"],
            "remotePort = %d" % s["internal"],
            "",
        ]
    return "\n".join(lines)


