def nginx_site(svc, domain, tls):
    head = []
    if tls:
        head = [
            "    listen %d ssl;" % svc["public"],
            "    ssl_certificate     %s/pubhelper.crt;" % NGINX_SSL_DIR,
            "    ssl_certificate_key %s/pubhelper.key;" % NGINX_SSL_DIR,
            "    ssl_protocols TLSv1.2 TLSv1.3;",
        ]
    else:
        head = ["    listen %d;" % svc["public"]]

    lines = ["# generated by pubhelper - %s" % (svc.get("name") or "service")]
    lines.append("server {")
    lines += head
    if domain:
        lines.append("    server_name %s;" % domain)
    if not tls:
        lines += [
            "    # 还没签证书，先跑 HTTP",
            "    location /.well-known/acme-challenge/ { root /var/www/acme; }",
        ]
    # 优先用现场探测结果；探测不出来再退回已知 TLS 端口表
    scheme = (svc.get("scheme") or "").strip().lower()
    if scheme in ("http", "https"):
        upstream_tls = (scheme == "https")
    else:
        upstream_tls = svc["port"] in TLS_UPSTREAM_PORTS
    lines += [
        "",
        "    client_max_body_size 0;",
        "",
        "    location / {",
        "        proxy_pass %s://127.0.0.1:%d;" % ("https" if upstream_tls else "http",
                                              svc["internal"]),
    ]
    if upstream_tls:
        lines += [
            "        # 源站是自签证书，不校验",
            "        proxy_ssl_verify off;",
            "        proxy_ssl_server_name on;",
        ]
    lines += [
        "        proxy_http_version 1.1;",
        "        proxy_set_header Upgrade $http_upgrade;",
        "        proxy_set_header Connection $ph_conn;",
        "        proxy_set_header Host $host;",
        "        proxy_set_header X-Real-IP $remote_addr;",
        "        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;",
        "        proxy_set_header X-Forwarded-Proto $scheme;",
        "        proxy_buffering off;",
        "        proxy_request_buffering off;",
        "        proxy_read_timeout 3600s;",
        "        proxy_send_timeout 3600s;",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


