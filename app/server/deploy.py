    def _ensure_acme(self):
        acme = "/root/.acme.sh/acme.sh"
        rc, _o, _e = self.ssh.run("test -x %s && %s --version 2>/dev/null | head -1" % (acme, acme),
                                  timeout=40)
        if rc == 0:
            self._log("服务器已有 acme.sh，直接使用")
            return
        local = self._acme_local()
        if local:
            self._log("上传内置 acme.sh（%.0f KB）" % (os.path.getsize(local) / 1024.0))
            self.ssh.put_file(local, "/root/acme.sh.new")
            self.sh("mkdir -p /root/.acme.sh && mv -f /root/acme.sh.new /root/.acme.sh/acme.sh && "
                    "chmod 755 /root/.acme.sh/acme.sh", timeout=60)
            return
        # 兜底：在线拉，全部带超时，绝不允许挂死
        self._log("本机没有内置 acme.sh，尝试从服务器下载（最长 90 秒）")
        urls = [
            "https://raw.githubusercontent.com/acmesh-official/acme.sh/master/acme.sh",
            "https://ghfast.top/https://raw.githubusercontent.com/acmesh-official/acme.sh/master/acme.sh",
            "https://ghproxy.net/https://raw.githubusercontent.com/acmesh-official/acme.sh/master/acme.sh",
        ]
        script = ["set +e", "mkdir -p /root/.acme.sh"]
        for u in urls:
            script.append(
                'curl -fsSL --connect-timeout 8 --max-time 90 -o /root/.acme.sh/acme.sh "%s" && '
                '[ $(stat -c %%s /root/.acme.sh/acme.sh 2>/dev/null || echo 0) -gt 50000 ] && '
                'echo ACME_OK && break' % u)
        script += ["chmod 755 /root/.acme.sh/acme.sh 2>/dev/null", "echo ACME_END"]
        out = self.sh("\n".join(script), timeout=320)
        if "ACME_OK" not in out:
            raise sshx.SSHError("获取 acme.sh 失败（GitHub 与镜像都不通）。"
                                "请把 acme.sh 放到 NAS 的 %s/bundle/ 后重试"
                                % self.data_dir)

    def _https_enabled(self):
        return bool(self.cfg.get("use_https")) and bool(self.domain)

    def st_cert(self):
        if not self._https_enabled():
            if self.domain:
                return "未启用 HTTPS，跳过证书（当前为 http://域名:端口）"
            return "未填域名，跳过证书（当前为 http://IP:端口）"
        self._ensure_acme()
        # webroot 权限：/var/www 本身也必须是 755，否则 nginx worker 连目录都进不去（403）
        self.sh("mkdir -p /var/www/acme/.well-known/acme-challenge; "
                "chmod 755 /var/www /var/www/acme /var/www/acme/.well-known "
                "/var/www/acme/.well-known/acme-challenge", timeout=60)
        self._check_webroot()

        acme = "/root/.acme.sh/acme.sh"
        script = [
            "set +e",
            "%s --set-default-ca --server letsencrypt >/dev/null 2>&1" % acme,
        ]
        if self._has_cert():
            self._log("已有证书，跳过签发（避免触发 Let's Encrypt 频率限制）")
        else:
            self._log("向 Let's Encrypt 申请 %s 的证书" % self.domain)
            script += [
                "%s --issue -d %s --webroot /var/www/acme 2>&1 | tail -12"
                % (acme, self.domain),
            ]
        script += [
            "%s --install-cert -d %s "
            "--key-file %s/pubhelper.key --fullchain-file %s/pubhelper.crt "
            "--reloadcmd 'systemctl reload nginx' >/dev/null 2>&1" % (acme, self.domain,
                                                                      NGINX_SSL_DIR, NGINX_SSL_DIR),
            "test -s %s/pubhelper.crt && test -s %s/pubhelper.key && echo CERT_OK"
            % (NGINX_SSL_DIR, NGINX_SSL_DIR),
        ]
        out = self.sh("\n".join(script), timeout=420)
        if "CERT_OK" not in out:
            tail = " | ".join((out or "").strip().splitlines()[-5:])
            raise sshx.SSHError(
                "证书签发失败。\n"
                "常见原因：\n"
                "  1) 域名 A 记录没指向本服务器（当前填的是 %s）\n"
                "  2) 云厂商安全组没放行 80 端口（HTTP-01 验证要用）\n"
                "  3) 同一域名本月签发次数超限\n"
                "服务器返回：%s" % (self.cfg["vps"]["host"], tail))
        self._install_renew_timer()
        # 有证书了，重刷站点为 HTTPS
        self._site_tls = True
        for svc in self.tcp_svcs:
            self._write_remote(
                "%s/pubhelper-site-%d.conf" % (NGINX_CONF_DIR, svc["public"]),
                nginx_site(svc, self.domain, True))
        rc, out, err = self.ssh.run("nginx -t 2>&1", timeout=60)
        if rc != 0:
            self._nginx_rollback()
            raise sshx.SSHError("启用 HTTPS 后 nginx 配置有误（已回滚）：%s" % (err or out))
        self.sh("systemctl reload nginx", timeout=120)
        return "证书已签发并启用"

    @staticmethod
    def _probe_http(url, timeout=12):
        """返回 HTTP 状态码；连不上/握手失败返回 000。"""
        try:
            r = subprocess.run(["curl", "-k", "-s", "-o", "/dev/null",
                                "-m", str(timeout), "-w", "%{http_code}", url],
                               capture_output=True, text=True, timeout=timeout + 4)
            return (r.stdout or "").strip() or "000"
        except Exception:
            return "000"

    def st_selftest(self):
        host = self.cfg["vps"]["host"].strip()
        # 自检走解析出的 IP 更可靠（避免域名 DNS 抖动）
        if self.cfg["vps"].get("ip"):
            self._log("自检目标：%s（%s 解析结果）" % (self.cfg["vps"]["ip"], host))
            host = self.cfg["vps"]["ip"]

        # 用「站点实际配置的协议」判断，而不是「打算用什么」。
        # 证书没签成时站点仍是 HTTP，按 HTTPS 去探只会拿到 000，误报成反代不通。
        primary = "https" if getattr(self, "_site_tls", None) else "http"
        other = "http" if primary == "https" else "https"

        lines, ok_n, bad = [], 0, []
        for svc in self.tcp_svcs:
            port = svc["public"]
            url = "%s://%s:%d/" % (primary, host, port)
            code = self._probe_http(url)
            if code in ("000", ""):
                # 换个协议再试一次：可能是证书缺失导致站点还是明文
                url2 = "%s://%s:%d/" % (other, host, port)
                code2 = self._probe_http(url2)
                if code2 not in ("000", ""):
                    self._log("端口 %d 的 %s 访问不通，但 %s 正常 —— 站点实际是 %s"
                              % (port, primary, other, other))
                    url, code = url2, code2

            good = code not in ("000", "")
            if good:
                ok_n += 1
            else:
                bad.append("%d→%s" % (port, code))
            lines.append({"name": svc.get("name") or str(svc["port"]),
                          "url": url, "code": code, "ok": good})

        if ok_n == 0:
            raise sshx.SSHError(
                "端口反代没通（%s）。\n"
                "000 代表连接层就没通，常见原因：\n"
                "  1) 云厂商安全组没放行这些端口（最常见）\n"
                "  2) 服务器防火墙拦截\n"
                "  3) frpc 隧道没建立（看「运行状态」里的隧道日志）"
                % "，".join(bad))
        if bad:
            self._log("部分端口自检未通过：%s" % "，".join(bad))

        self.result = {"urls": lines, "domain": self.domain,
                       "frp_bind": self.frp_bind,
                       "internal": [{"port": s["port"], "internal": s["internal"]}
                                    for s in self.services]}
        return "%d/%d 个端口自检通过" % (ok_n, len(self.tcp_svcs))

    # ---------- 卸载 ----------
    def uninstall(self, purge_cert=False):
        """清理两端：本机 frpc 进程/配置/日志 + 服务器的 frps 与反代站点。

        nginx 本体与证书默认保留（证书重签会触发 Let's Encrypt 频率限制）。
        """
        out = []

        # ---------- 本机（NAS） ----------
        base = os.path.join(self.data_dir, "frp")
        pidf = os.path.join(base, "frpc.pid")

        # 先摘掉 systemd 托管，否则删了目录它还会一直重启
        if os.path.isfile(FRPC_UNIT_PATH):
            try:
                for cmd in (["systemctl", "stop", FRPC_UNIT_NAME],
                            ["systemctl", "disable", FRPC_UNIT_NAME]):
                    subprocess.run(cmd, capture_output=True, text=True, timeout=60)
                os.unlink(FRPC_UNIT_PATH)
                subprocess.run(["systemctl", "daemon-reload"],
                               capture_output=True, timeout=60)
                out.append("已移除 systemd 服务（%s）" % FRPC_UNIT_NAME)
            except Exception as e:
                out.append("移除 systemd 服务失败：%s" % e)

        pid = 0
        try:
            if os.path.isfile(pidf):
                pid = int((open(pidf).read() or "0").strip() or 0)
        except Exception:
            pid = 0
        if pid:
            try:
                os.kill(pid, 15)
                time.sleep(1.5)
                try:
                    os.kill(pid, 0)
                    os.kill(pid, 9)
                except Exception:
                    pass
                out.append("已停止本机 frpc（pid %d）" % pid)
            except Exception as e:
                out.append("停止本机 frpc 失败：%s" % e)
        # 兜底：按命令行再扫一遍，防止 pid 文件丢失
        try:
            r = subprocess.run(["pkill", "-f", base + "/frpc"],
                               capture_output=True, timeout=10)
            if r.returncode == 0:
                out.append("已清理残留的 frpc 进程")
        except Exception:
            pass
        if os.path.isdir(base):
            shutil.rmtree(base, ignore_errors=True)
            out.append("已删除本机隧道配置/日志目录：%s" % base)
        else:
            out.append("本机没有残留的隧道配置")

        # ---------- 服务器 ----------
        vps = self.cfg.get("vps") or {}
        if not (vps.get("host") or "").strip():
            out.append("未配置服务器，跳过服务器侧清理")
            return out
        ssh = None
        try:
            ssh = sshx.SSH(host=vps["host"], port=vps.get("port") or 22,
                           user=vps.get("user") or "root", password=self.password,
                           keyfile=vps.get("keyfile") or "",
                           family=vps.get("family") or "auto",
                           workdir=os.path.join(self.data_dir, "ssh"), timeout=90)
            out.append("已连接服务器 %s" % vps["host"])
            ssh.run("systemctl stop frps 2>/dev/null; "
                    "systemctl disable frps 2>/dev/null; true")
            ssh.run("rm -f /usr/local/bin/frps /etc/frp/frps.toml "
                    "/etc/systemd/system/frps.service; systemctl daemon-reload 2>/dev/null; true")
            ssh.run("systemctl stop pubhelper-acme-renew.timer 2>/dev/null; "
                    "systemctl disable pubhelper-acme-renew.timer 2>/dev/null; "
                    "rm -f /etc/systemd/system/pubhelper-acme-renew.timer "
                    "/etc/systemd/system/pubhelper-acme-renew.service; "
                    "crontab -l 2>/dev/null | grep -v 'acme.sh --cron' | crontab - 2>/dev/null; "
                    "systemctl daemon-reload 2>/dev/null; true")
            out.append("已移除证书自动续期任务")
            out.append("已停止并删除服务器上的 frps（服务/配置/二进制）")
            ssh.run("rm -f %s/pubhelper-*.conf %s/00-pubhelper-map.conf; "
                    "systemctl reload nginx 2>/dev/null; true"
                    % (NGINX_CONF_DIR, NGINX_CONF_DIR))
            out.append("已删除服务器上的反向代理站点")
            if purge_cert:
                ssh.run("rm -rf %s/pubhelper.crt %s/pubhelper.key %s/pubhelper.crt "
                        "%s/pubhelper.key /var/www/acme; true"
                        % (NGINX_SSL_DIR, NGINX_SSL_DIR, NGINX_SSL_DIR, NGINX_SSL_DIR))
                ssh.run("/root/.acme.sh/acme.sh --remove -d %s >/dev/null 2>&1; true"
                        % (self.cfg.get("domain") or ""))
                out.append("已删除服务器上的证书与 ACME 记录")
            else:
                out.append("证书与 nginx 本体保留（避免重复签发触发频率限制）")
            try:
                ssh.run("rm -f /tmp/pubhelper-frp.tar.gz; true", timeout=30)
            except Exception:
                pass
        except Exception as e:
            out.append("服务器侧清理失败：%s" % e)
        finally:
            if ssh:
                ssh.close()
        return out


